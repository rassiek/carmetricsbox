#!/usr/bin/env python3
"""Gzip the display's web page into firmware/CarMetricsDisplay/WebPage.h (committed,
so the sketch also builds in the Arduino IDE without this step)."""
import gzip, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "firmware", "CarMetricsDisplay", "web", "index.html")
out = os.path.join(root, "firmware", "CarMetricsDisplay", "WebPage.h")
data = gzip.compress(open(src, "rb").read(), 9, mtime=0)
lines = ["// Generated by tools/build_display_web.py from web/index.html - do not edit.", "#pragma once", "#include <stdint.h>",
         f"const uint8_t WEB_PAGE_GZ[{len(data)}] = {{"]
for i in range(0, len(data), 24):
    lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
lines.append("};")
new = "\n".join(lines) + "\n"
if not os.path.exists(out) or open(out).read() != new:
    open(out, "w").write(new)
print(f"display web page: {os.path.getsize(src)} bytes -> {len(data)} gzipped")
