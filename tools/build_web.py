#!/usr/bin/env python3
"""Build the CarMetrics web app for the ESP32.

1. gzips every file in web/ into firmware/libraries/CarMetricsCore/src/WebApp.h:
   the web app is part of the firmware (served gzipped, always matches it)
2. if mklittlefs is found, writes build/littlefs.bin: an empty file system for
   the full-flash file (the board keeps alarm recordings and upload data there)

Usage:  python3 tools/build_web.py [--mklittlefs PATH]
"""
import argparse
import glob
import gzip
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "web")
DATA = os.path.join(ROOT, "firmware", "CarMetrics", "data")
OUT = os.path.join(DATA, "www")
BUILD = os.path.join(ROOT, "build")
FS_SIZE = 0x90000  # must match the spiffs partition in partitions.csv (0x350000)


def find_mklittlefs(explicit):
    if explicit:
        return explicit
    found = shutil.which("mklittlefs")
    if found:
        return found
    patterns = [
        os.path.expanduser("~/Arduino/hardware/espressif/esp32/tools/mklittlefs/mklittlefs*"),
        os.path.expanduser("~/.arduino15/packages/esp32/tools/mklittlefs/*/mklittlefs*"),
        os.path.expanduser("~/Library/Arduino15/packages/esp32/tools/mklittlefs/*/mklittlefs*"),
        os.path.expandvars(r"%LOCALAPPDATA%\Arduino15\packages\esp32\tools\mklittlefs\*\mklittlefs.exe"),
        os.path.expanduser("~/.platformio/packages/tool-mklittlefs/mklittlefs*"),
    ]
    for p in patterns:
        hits = [h for h in glob.glob(p) if os.path.isfile(h)]
        if hits:
            return sorted(hits)[-1]
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mklittlefs", help="path to the mklittlefs tool")
    ap.add_argument("--line", default="", help="ignored since 5.3 (one version for every board)")
    ap.add_argument("--fs-size", default=hex(FS_SIZE), help="LittleFS partition size (5.1: 0x90000, 5.2: 0x1C0000)")
    ap.add_argument("--data", default=os.path.join(BUILD, "fsdata"), help="folder for the (empty) file system image")
    ap.add_argument("--out", default=os.path.join(BUILD, "littlefs.bin"), help="LittleFS image to write")
    args = ap.parse_args()

    # The firmware's release label (Config.h FW_VERSION) is baked into the web
    # app, so the pages can warn when the firmware and web app don't match.
    import re
    cfg = open(os.path.join(ROOT, "firmware", "libraries", "CarMetricsCore", "src", "Config.h"), encoding="utf-8").read()
    version = re.search(r'#define FW_VERSION "([^"]+)"', cfg).group(1)
    data_dir, out_dir = args.data, os.path.join(args.data, "www")
    print(f"release {version}")

    # 5.4: the web app is built into the firmware (CarMetricsCore/src/WebApp.h), so a
    # Wi-Fi update is one file and the pages always match the firmware. Files are
    # stored gzipped; presets stay plain JSON (the firmware reads them itself).
    files = []
    for root, _, names in os.walk(SRC):
        for name in sorted(names):
            src = os.path.join(root, name)
            rel = os.path.relpath(src, SRC).replace(os.sep, "/")
            if name.startswith(".") or rel.endswith(".md"):
                continue
            raw = open(src, "rb").read().replace(b"__CM_VERSION__", version.encode())
            gz = not rel.startswith("presets/")
            body = gzip.compress(raw, compresslevel=9, mtime=0) if gz else raw
            files.append((rel, body, gz, len(raw)))
    files.sort()
    mime = {".html": "text/html", ".js": "application/javascript", ".css": "text/css", ".png": "image/png", ".json": "application/json", ".svg": "image/svg+xml"}
    out = ["// Generated by tools/build_web.py from web/ - do not edit. The web app, built into the firmware.",
           "#pragma once", "#include <Arduino.h>", "#include \"Web.h\"", ""]
    for i, (rel, body, gz, n) in enumerate(files):
        out.append(f"static const uint8_t kWf{i}[] PROGMEM = {{" + ",".join(str(b) for b in body) + "};")
    out.append("static const Web::File kWebFiles[] = {")
    for i, (rel, body, gz, n) in enumerate(files):
        out.append(f'  {{"/{rel}", "{mime.get(os.path.splitext(rel)[1], "application/octet-stream")}", kWf{i}, {len(body)}, {"true" if gz else "false"}}},')
    out.append("};")
    out.append(f"static const size_t kWebFileCount = {len(files)};")
    header = os.path.join(ROOT, "firmware", "libraries", "CarMetricsCore", "src", "WebApp.h")
    open(header, "w").write("\n".join(out) + "\n")
    total_in = sum(f[3] for f in files); total_out = sum(len(f[1]) for f in files)
    for rel, body, gz, n in files:
        print(f"  {rel:24s} {n:8d} -> {len(body):7d}")
    print(f"web app: {total_in} bytes -> {total_out} bytes in the firmware ({header})")

    # The LittleFS partition only holds data the board writes (alarm recordings,
    # offline upload buffer): the full-flash file carries an empty file system.
    shutil.rmtree(data_dir, ignore_errors=True)
    os.makedirs(data_dir)
    tool = find_mklittlefs(args.mklittlefs)
    if not tool:
        print("mklittlefs not found - skipped littlefs.bin (data/ folder is ready for the IDE upload plugin)")
        return 0
    os.makedirs(BUILD, exist_ok=True)
    image = args.out
    os.makedirs(os.path.dirname(image), exist_ok=True)
    subprocess.check_call([tool, "-c", data_dir, "-b", "4096", "-p", "256", "-s", str(int(args.fs_size, 0)), image],
                          stdout=subprocess.DEVNULL)
    data = open(image, "rb").read()
    print(f"filesystem image (empty, for the full-flash file): {image} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
